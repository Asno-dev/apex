// ponytail: v2 deprecated (410), using v3.1 for everything
const COMPOSIO_API_BASE = 'https://backend.composio.dev/api/v3.1';

function getApiBase(): string {
  if (typeof window !== 'undefined' && (window.location.hostname === 'localhost' || window.location.hostname === '127.0.0.1')) {
    return '/api/composio/api/v3.1';
  }
  return COMPOSIO_API_BASE;
}

export async function composioInitiateConnection(
  apiKey: string,
  userId: string,
  authConfigId: string,
  toolSlug?: string
): Promise<{ redirectUrl: string; connectionId?: string }> {
  // ponytail: v3.1 uses /link endpoint with snake_case fields
  const apiBase = getApiBase();
  const response = await fetch(`${apiBase}/connected_accounts/link`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': apiKey,
    },
    body: JSON.stringify({
      auth_config_id: authConfigId,
      user_id: userId,
    }),
  });

  if (!response.ok) {
    let errMsg = `Connection failed (HTTP ${response.status})`;
    try {
      const data = await response.json();
      errMsg = data.error?.message || data.message || data.error || data.detail || errMsg;
    } catch { /* keep default */ }
    throw new Error(errMsg);
  }

  const data = await response.json();
  const redirectUrl = data.redirect_url || data.redirectUrl || '';
  const connectionId = data.connected_account_id || data.connectionStatus?.id || data.id || '';

  return { redirectUrl, connectionId };
}

export async function composioGetConnectedAccounts(
  apiKey: string,
  userId: string
): Promise<ComposioConnectedAccount[]> {
  try {
    const apiBase = getApiBase();
    const response = await fetch(`${apiBase}/connected_accounts?user_uuid=${userId}`, {
      headers: {
        'x-api-key': apiKey,
      },
    });

    if (!response.ok) return [];

    const data = await response.json();
    return (data.items || []).map((item: any) => ({
      id: item.id,
      toolSlug: (item.appName || item.appUniqueId || '').toLowerCase(),
      status: item.status || 'active',
      createdAt: item.createdAt || '',
    }));
  } catch {
    return [];
  }
}

// Check the status of a specific connection
export async function composioCheckConnectionStatus(
  apiKey: string,
  connectionId: string
): Promise<string> {
  try {
    const apiBase = getApiBase();
    const response = await fetch(`${apiBase}/connected_accounts/${connectionId}`, {
      headers: {
        'x-api-key': apiKey,
      },
    });

    if (!response.ok) return 'UNKNOWN';

    const data = await response.json();
    return data.status || data.connectionStatus?.status || 'ACTIVE';
  } catch {
    return 'UNKNOWN';
  }
}

export async function composioGetToolsForToolkit(
  apiKey: string,
  toolkitSlug: string
): Promise<ComposioToolDefinition[]> {
  try {
    const apiBase = getApiBase();
    const response = await fetch(`${apiBase}/tools?toolkit_slug=${encodeURIComponent(toolkitSlug)}`, {
      headers: {
        'x-api-key': apiKey,
      },
    });
    if (!response.ok) return [];
    const data = await response.json();
    return data.items || data.tools || (Array.isArray(data) ? data : []);
  } catch (err) {
    console.error(`Failed to fetch tools for toolkit ${toolkitSlug}:`, err);
    return [];
  }
}

export async function composioExecuteTool(
  apiKey: string,
  toolSlug: string,
  userId: string,
  args: Record<string, any>
): Promise<any> {
  const apiBase = getApiBase();
  const encodedSlug = encodeURIComponent(toolSlug);

  const response = await fetch(`${apiBase}/tools/execute/${encodedSlug}`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': apiKey,
    },
    body: JSON.stringify({
      user_id: userId,
      arguments: args,
    }),
  });

  if (!response.ok) {
    let errMsg = `Execution failed (HTTP ${response.status})`;
    try {
      const errData = await response.json();
      errMsg = errData.message || errData.error || errData.detail || errMsg;
    } catch {
      // keep default error message
    }
    throw new Error(errMsg);
  }

  const result = await response.json();
  return result.data || result.response || result;
}
