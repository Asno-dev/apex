export function getComposioTools(): ComposioTool[] {
  return COMPOSIO_TOOLS.map(t => ({
    ...t,
    actions: COMPOSIO_ACTION_SLUGS[t.slug] || [],
  }));
}

export function getToolBySlug(slug: string): ComposioTool | undefined {
  return getComposioTools().find(t => t.slug === slug);
}

export function getToolActions(slug: string): string[] {
  return COMPOSIO_ACTION_SLUGS[slug] || [];
}

export function searchTools(query: string): ComposioTool[] {
  const q = query.toLowerCase().trim();
  if (!q) return COMPOSIO_TOOLS;
  return COMPOSIO_TOOLS.filter(
    t =>
      t.name.toLowerCase().includes(q) ||
      t.slug.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q)
  );
}

